def run_audit(cfg) -> dict:
    """Run the full data audit and write its report.

    Parameters
    ----------
    cfg : Config
        Resolved project configuration.

    Returns
    -------
    dict
        The complete audit report, also written to
        ``outputs/reports/data_audit.json``.
    """
    logger.info("Running data audit")

    df, cleaning = load_training_data(cfg, drop_invalid=True)
    raw_df, _ = load_training_data(cfg, drop_invalid=False)

    feature_cols = [
        "elevation", "slope", "aspect", "plan_curv", "profile_curv",
        "TWI", "SPI", "dist_drainage", "dist_road", "dist_fault",
        "NDVI", "LULC", "lithology", "rainfall",
    ]
    forbidden = list(cfg.get("features", "forbidden_columns", default=[]))
    sentinel = float(cfg.get("features", "lithology_unmapped_code", default=-1))
    flat_tol = float(cfg.get("features", "flat_slope_tolerance", default=0.0))

    report: dict = {"cleaning": cleaning.as_dict()}

    logger.info("--- raster grid validation ---")
    grid = validate_grid_alignment(cfg)
    report["grid"] = grid.as_dict()
    report["district_footprint"] = district_mask_stats(cfg)

    logger.info("--- dataset composition ---")
    report["class_balance"] = _audit_class_balance(df)
    report["class_balance_raw_file"] = _audit_class_balance(raw_df)
    report["completeness"] = _audit_completeness(df, feature_cols)

    logger.info("--- label leakage check ---")
    report["label_leakage"] = _audit_label_leakage(df, forbidden)

    logger.info("--- categorical factors ---")
    report["lithology_classes"] = _audit_categorical(df, "lithology")
    report["lulc_classes"] = _audit_categorical(df, "LULC")
    report["lithology_coverage_gap"] = _audit_lithology_gap(df, sentinel)
    report["trivial_negatives"] = _audit_trivial_negatives(df)

    logger.info("--- encoding artefacts ---")
    report["aspect_flat_cells"] = _audit_aspect_flat(df, flat_tol)
    report["skew"] = _audit_skew(df, ["SPI", "TWI", "dist_road", "dist_fault"])

    logger.info("--- spatial structure ---")
    report["spatial_clustering"] = _audit_spatial_clustering(df)
    variogram = estimate_autocorrelation_range(
        df[["X", "Y"]].to_numpy(dtype="float64"),
        df["label"].to_numpy(dtype="float64"),
    )
    report["autocorrelation"] = variogram.as_dict()

    # The block size the rest of the pipeline will use.
    floor = float(cfg.get("cross_validation", "block_size_min_m", default=2000))
    block = max(variogram.range_m, floor)
    report["recommended_block_size_m"] = round(block, 0)
    logger.info(
        "Recommended spatial CV block size: %.0f m (range=%.0f m, floor=%.0f m)",
        block,
        variogram.range_m,
        floor,
    )

    logger.info("--- rainfall layer disambiguation ---")
    report["rainfall_source"] = _audit_rainfall_source(cfg, df)

    out_path = cfg.reports_dir / "data_audit.json"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8") as handle:
        json.dump(report, handle, indent=2, default=str)
    logger.info("Audit report written: %s", out_path)

    return report
