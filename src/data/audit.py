"""Reproducible audit of the delivered data assets.

Every data finding quoted in ``docs/data_dictionary.md`` and
``docs/methodology.md`` is produced here, so that a claim in the documentation
can be regenerated by running one command rather than trusted because someone
wrote it down.

The audit deliberately *reports* rather than *fixes*. Several findings — the
lithology coverage gap, the flat-cell aspect convention, the reporting bias in
``dist_road`` — are limitations to be documented and worked around downstream,
not defects to be silently patched here.

It also produces one number the rest of the pipeline consumes: the empirical
spatial autocorrelation range of the target, which sets the block size for
spatial cross-validation in Stage 3.
"""

from __future__ import annotations

import json
from dataclasses import dataclass

import numpy as np
import pandas as pd
from scipy.spatial import cKDTree
from scipy.spatial.distance import pdist

from src.data.loaders import load_training_data, sample_factors_at_points
from src.data.validation import district_mask_stats, validate_grid_alignment
from src.utils.logging_setup import get_logger

__all__ = ["run_audit", "empirical_variogram", "estimate_autocorrelation_range"]

logger = get_logger(__name__)


