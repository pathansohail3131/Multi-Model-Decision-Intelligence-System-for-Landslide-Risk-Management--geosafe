@dataclass
class VariogramResult:
    """Empirical variogram and the range estimated from it.

    Attributes
    ----------
    lag_centres : numpy.ndarray
        Distance at the centre of each lag bin, in metres.
    semivariance : numpy.ndarray
        Semivariance in each bin.
    counts : numpy.ndarray
        Number of point pairs contributing to each bin.
    sill : float
        Plateau semivariance, taken as the overall variance of the values.
    range_m : float
        Distance at which semivariance first reaches ``sill_fraction`` of the
        sill — the separation beyond which points are effectively independent.
    sill_fraction : float
        Fraction of the sill used for the range estimate.
    """

    lag_centres: np.ndarray
    semivariance: np.ndarray
    counts: np.ndarray
    sill: float
    range_m: float
    sill_fraction: float

    def as_dict(self) -> dict:
        """Return a JSON-serialisable summary."""
        return {
            "lag_centres_m": [round(float(v), 1) for v in self.lag_centres],
            "semivariance": [round(float(v), 6) for v in self.semivariance],
            "pair_counts": [int(v) for v in self.counts],
            "sill": round(float(self.sill), 6),
            "sill_fraction_used": self.sill_fraction,
            "range_m": round(float(self.range_m), 1),
        }


def empirical_variogram(
    coords: np.ndarray,
    values: np.ndarray,
    n_lags: int = 30,
    max_dist: float = 30_000.0,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, float]:
    """Compute a binned empirical semivariogram.

    Semivariance at lag *h* is ``0.5 * mean((z_i - z_j)^2)`` over all point
    pairs separated by approximately *h*. It starts low (nearby points are
    similar) and rises to a plateau — the sill — at the separation beyond which
    points carry no information about each other.

    Parameters
    ----------
    coords : numpy.ndarray, shape (n, 2)
        Projected coordinates in metres.
    values : numpy.ndarray, shape (n,)
        Values to compute the variogram of. Here, the binary target.
    n_lags : int, default 30
        Number of distance bins.
    max_dist : float, default 30000.0
        Maximum separation considered, in metres. Pairs beyond this are
        ignored; the district's own extent (~108 x 168 km) means very large
        lags are supported by few, geometrically special pairs.

    Returns
    -------
    lag_centres, semivariance, counts, sill

    Notes
    -----
    Uses the full pairwise distance matrix via :func:`scipy.spatial.distance.pdist`.
    At ~4,900 points that is ~12 M pairs, which is comfortable in memory and
    avoids the sampling noise of a subsampled estimator.
    """
    distances = pdist(coords)
    # Squared differences for the same pair ordering as pdist.
    diffs = pdist(values.reshape(-1, 1), metric="sqeuclidean")

    edges = np.linspace(0.0, max_dist, n_lags + 1)
    # np.digitize returns 0 for below-range and n_lags+1 for above-range.
    bin_index = np.digitize(distances, edges) - 1
    within = (bin_index >= 0) & (bin_index < n_lags)

    counts = np.bincount(bin_index[within], minlength=n_lags)
    sums = np.bincount(bin_index[within], weights=diffs[within], minlength=n_lags)

    with np.errstate(invalid="ignore", divide="ignore"):
        semivariance = 0.5 * sums / counts
    semivariance = np.where(counts > 0, semivariance, np.nan)

    lag_centres = 0.5 * (edges[:-1] + edges[1:])
    sill = float(np.var(values))
    return lag_centres, semivariance, counts, sill


def estimate_autocorrelation_range(
    coords: np.ndarray,
    values: np.ndarray,
    n_lags: int = 30,
    max_dist: float = 30_000.0,
    sill_fraction: float = 0.95,
) -> VariogramResult:
    """Estimate the spatial autocorrelation range of a variable.

    The range is the smallest lag at which the empirical semivariance first
    reaches ``sill_fraction`` of the sill. Beyond it, two observations are
    effectively independent, which makes it the natural minimum side length for
    a cross-validation block: blocks smaller than the range leave training and
    test points correlated across the fold boundary, which is exactly the
    leakage spatial blocking exists to remove.

    Parameters
    ----------
    coords : numpy.ndarray, shape (n, 2)
        Projected coordinates in metres.
    values : numpy.ndarray, shape (n,)
        Values whose autocorrelation is being measured.
    n_lags : int, default 30
        Number of distance bins.
    max_dist : float, default 30000.0
        Maximum separation considered, in metres.
    sill_fraction : float, default 0.95
        Fraction of the sill defining the range.

    Returns
    -------
    VariogramResult
        The variogram and its estimated range. If the semivariance never
        reaches the threshold within ``max_dist``, ``range_m`` is set to
        ``max_dist`` and a warning is logged, since the true range then lies
        beyond the window examined.
    """
    lag_centres, semivariance, counts, sill = empirical_variogram(
        coords, values, n_lags=n_lags, max_dist=max_dist
    )
    target = sill_fraction * sill
    reached = np.flatnonzero(np.nan_to_num(semivariance, nan=-np.inf) >= target)

    if reached.size:
        range_m = float(lag_centres[reached[0]])
    else:
        range_m = float(max_dist)
        logger.warning(
            "Semivariance never reached %.0f%% of the sill within %.0f m; "
            "range is at least that far and the block size floor will govern.",
            100 * sill_fraction,
            max_dist,
        )

    logger.info(
        "Spatial autocorrelation range of the target: ~%.0f m "
        "(sill=%.5f, threshold=%.5f)",
        range_m,
        sill,
        target,
    )
    return VariogramResult(
        lag_centres=lag_centres,
        semivariance=semivariance,
        counts=counts,
        sill=sill,
        range_m=range_m,
        sill_fraction=sill_fraction,
    )


