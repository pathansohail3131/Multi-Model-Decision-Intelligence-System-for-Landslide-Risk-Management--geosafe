def _audit_class_balance(df: pd.DataFrame) -> dict:
    """Class counts, ratio, and positives by taluk."""
    n_pos = int(df["label"].sum())
    n_neg = int(len(df) - n_pos)
    by_taluk = (
        df.loc[df["label"] == 1, "taluk"].value_counts().to_dict()
        if "taluk" in df
        else {}
    )
    return {
        "n_samples": int(len(df)),
        "n_positive": n_pos,
        "n_negative": n_neg,
        "imbalance_ratio": round(n_neg / max(n_pos, 1), 2),
        "positive_rate": round(n_pos / max(len(df), 1), 4),
        "positives_by_taluk": {str(k): int(v) for k, v in by_taluk.items()},
    }


def _audit_completeness(df: pd.DataFrame, feature_cols: list[str]) -> dict:
    """Missing values, infinities, and duplicate rows."""
    nan_counts = {c: int(df[c].isna().sum()) for c in feature_cols}
    inf_counts = {
        c: int(np.isinf(df[c].to_numpy(dtype="float64")).sum())
        for c in feature_cols
        if pd.api.types.is_numeric_dtype(df[c])
    }
    return {
        "missing_by_feature": {k: v for k, v in nan_counts.items() if v},
        "total_missing_in_features": int(sum(nan_counts.values())),
        "infinite_by_feature": {k: v for k, v in inf_counts.items() if v},
        "duplicate_coordinate_pairs": int(df.duplicated(subset=["X", "Y"]).sum()),
        "duplicate_feature_rows": int(df.duplicated(subset=feature_cols).sum()),
    }


def _audit_label_leakage(df: pd.DataFrame, forbidden: list[str]) -> dict:
    """Confirm the forbidden columns really are label-separating.

    A column that is non-null on exactly the positive class perfectly separates
    the classes. This section proves the blocklist is necessary rather than
    precautionary.
    """
    out = {}
    for col in forbidden:
        if col not in df.columns:
            continue
        non_null = df[col].notna()
        if non_null.all():
            out[col] = {"separates_classes": False, "reason": "no missing values"}
            continue
        pos_rate_present = float(df.loc[non_null, "label"].mean())
        pos_rate_absent = float(df.loc[~non_null, "label"].mean())
        out[col] = {
            "non_null_count": int(non_null.sum()),
            "null_count": int((~non_null).sum()),
            "positive_rate_where_present": round(pos_rate_present, 4),
            "positive_rate_where_absent": round(pos_rate_absent, 4),
            "separates_classes": bool(
                pos_rate_present == 1.0 and pos_rate_absent == 0.0
            ),
        }
    return out


def _audit_categorical(df: pd.DataFrame, column: str) -> dict:
    """Per-class counts and landslide rates for a categorical factor."""
    grouped = df.groupby(column)["label"].agg(["size", "sum", "mean"])
    return {
        str(code): {
            "n": int(row["size"]),
            "positives": int(row["sum"]),
            "positive_rate": round(float(row["mean"]), 4),
        }
        for code, row in grouped.iterrows()
    }


def _audit_lithology_gap(df: pd.DataFrame, sentinel: float) -> dict:
    """Characterise the lithology coverage gap.

    Tests whether the sentinel is randomly missing or spatially structured, by
    comparing the affected samples' physical setting against everything else.
    A coverage gap that coincides with a distinct physical environment is
    confounded with the outcome, which changes how it must be handled.
    """
    gap = df["lithology"] == sentinel
    if not gap.any():
        return {"present": False}

    compare_cols = [
        c
        for c in ("elevation", "slope", "rainfall", "dist_road", "NDVI", "dist_drainage")
        if c in df.columns
    ]
    means = df.groupby(gap)[compare_cols].mean()
    return {
        "present": True,
        "n": int(gap.sum()),
        "n_positive": int(df.loc[gap, "label"].sum()),
        "positive_rate": round(float(df.loc[gap, "label"].mean()), 4),
        "baseline_positive_rate": round(float(df["label"].mean()), 4),
        "taluks_of_positives": {
            str(k): int(v)
            for k, v in df.loc[gap & (df["label"] == 1), "taluk"]
            .value_counts()
            .items()
        }
        if "taluk" in df
        else {},
        "mean_comparison": {
            col: {
                "gap": round(float(means.loc[True, col]), 3),
                "mapped": round(float(means.loc[False, col]), 3),
            }
            for col in compare_cols
        },
        "x_range_gap": [
            round(float(df.loc[gap, "X"].min()), 0),
            round(float(df.loc[gap, "X"].max()), 0),
        ],
        "x_range_all": [
            round(float(df["X"].min()), 0),
            round(float(df["X"].max()), 0),
        ],
    }


def _audit_aspect_flat(df: pd.DataFrame, tolerance: float) -> dict:
    """Detect the terrain software's flat-cell aspect placeholder."""
    flat = df["slope"] <= tolerance
    if not flat.any():
        return {"n_flat": 0}
    values = df.loc[flat, "aspect"]
    counts = values.value_counts()
    dominant = float(counts.index[0])
    return {
        "n_flat": int(flat.sum()),
        "distinct_aspect_values_on_flat": int(values.nunique()),
        "dominant_aspect_value": dominant,
        "dominant_share": round(float(counts.iloc[0] / len(values)), 4),
        "is_placeholder": bool(values.nunique() == 1),
        "n_positive_flat": int(df.loc[flat, "label"].sum()),
    }


def _audit_skew(df: pd.DataFrame, columns: list[str]) -> dict:
    """Raw vs log1p skew for heavily skewed positive-valued factors."""
    out = {}
    for col in columns:
        if col not in df.columns:
            continue
        series = df[col].astype("float64")
        entry = {
            "min": round(float(series.min()), 6),
            "max": round(float(series.max()), 2),
            "skew_raw": round(float(series.skew()), 2),
        }
        if (series >= 0).all():
            entry["skew_log1p"] = round(float(np.log1p(series).skew()), 2)
        out[col] = entry
    return out


def _audit_spatial_clustering(df: pd.DataFrame) -> dict:
    """Measure clustering of positives and the negative-sampling buffer."""
    pos = df.loc[df["label"] == 1, ["X", "Y"]].to_numpy()
    neg = df.loc[df["label"] == 0, ["X", "Y"]].to_numpy()

    # Nearest positive to each positive (k=2 skips the point itself).
    d_pp = cKDTree(pos).query(pos, k=2)[0][:, 1]
    # Nearest negative to each positive: reveals the exclusion buffer.
    d_pn = cKDTree(neg).query(pos)[0]

    return {
        "positive_to_positive": {
            "min_m": round(float(d_pp.min()), 2),
            "median_m": round(float(np.median(d_pp)), 1),
            "mean_m": round(float(d_pp.mean()), 1),
            "within_100m": int((d_pp < 100).sum()),
            "within_500m": int((d_pp < 500).sum()),
            "n_positives": int(len(pos)),
        },
        "positive_to_negative": {
            "min_m": round(float(d_pn.min()), 2),
            "median_m": round(float(np.median(d_pn)), 1),
            "inferred_exclusion_buffer_m": round(float(d_pn.min()), 0),
        },
    }


def _audit_rainfall_source(cfg, df: pd.DataFrame) -> dict:
    """Determine which rainfall raster the training CSV was sampled from.

    The processed directory holds two candidate rainfall layers. If the CSV was
    built from one and inference runs on the other, training and prediction sit
    on different distributions — with no error raised and no visible artefact,
    only a quietly wrong map. This resolves the ambiguity by re-sampling both
    at the training coordinates and comparing against the stored column.
    """
    candidates = {
        "rainfall_5yr_avg_aligned": "rainfall_uk_5yr_avg_aligned.tif",
        "rainfall_aligned": "rainfall_uk_aligned.tif",
    }
    stored = df["rainfall"].to_numpy(dtype="float64")
    processed = cfg.processed_dir
    results = {}

    from src.data.loaders import sample_raster_at_points

    xs = df["X"].to_numpy()
    ys = df["Y"].to_numpy()
    for label, filename in candidates.items():
        path = processed / filename
        if not path.exists():
            results[label] = {"available": False}
            continue
        sampled = sample_raster_at_points(path, xs, ys)
        both = np.isfinite(sampled) & np.isfinite(stored)
        if not both.any():
            results[label] = {"available": True, "comparable": 0}
            continue
        diff = np.abs(sampled[both] - stored[both])
        results[label] = {
            "available": True,
            "comparable": int(both.sum()),
            "max_abs_diff": round(float(diff.max()), 4),
            "mean_abs_diff": round(float(diff.mean()), 4),
            "fraction_matching_1e-2": round(float((diff < 1e-2).mean()), 4),
            "correlation": round(
                float(np.corrcoef(sampled[both], stored[both])[0, 1]), 6
            ),
        }

    available = {k: v for k, v in results.items() if v.get("available")}
    best = (
        min(available, key=lambda k: available[k].get("mean_abs_diff", np.inf))
        if available
        else None
    )
    configured = cfg.get("rasters", "rainfall")
    return {
        "candidates": results,
        "best_match": best,
        "configured": configured,
        "configured_is_best_match": (
            best is not None and candidates.get(best) == configured
        ),
    }


def _audit_trivial_negatives(df: pd.DataFrame, water_class: float = 80.0) -> dict:
    """Quantify negatives that are trivially separable.

    Permanent water cannot fail. Samples there are correct negatives but teach
    the model nothing, and they inflate every metric slightly by padding the
    easy end of the majority class. Reported so the Stage 2 decision to keep or
    drop them is made on evidence.
    """
    if "LULC" not in df.columns:
        return {}
    water = df["LULC"] == water_class
    return {
        "water_class": water_class,
        "n": int(water.sum()),
        "n_positive": int(df.loc[water, "label"].sum()),
        "share_of_negatives": round(
            float(water.sum() / max((df["label"] == 0).sum(), 1)), 4
        ),
        "mean_slope": round(float(df.loc[water, "slope"].mean()), 2)
        if water.any()
        else None,
    }


